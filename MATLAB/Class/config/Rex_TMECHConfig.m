function config = Rex_TMECHConfig()
    %REX_TMECHCONFIG Define the TMECH 1 kHz logger schema.
    % Time values are in ms, angles are in degrees, and torque uses CSV units.
    mapping = { ...
        'Time',                'time_ms'; ...
        'ActualTime',          'actual_time_ms'; ...
        'Drift',               'drift_ms'; ...
        'Left.Angle',          'L_deg'; ...
        'Right.Angle',         'R_deg'; ...
        'Assisted.Angle',      'M_deg'; ...
        'Axial.Torque',        'Torque_axis'; ...
        'Left.Torque',         'Torque_CAN_L'; ...
        'Right.Torque',        'Torque_CAN_R'; ...
        'Nominal.Angle',       'q_nominal_deg'; ...
        'Compensation.Torque', 'q_compensation'; ...
        'sync_state',          'sync_state'};

    config.ProjectType = 'Rex_TMECH';
    config.Fields = mapping(:, 1);
    config.ColumnNames = mapping(:, 2);
end
