function config = PawClearanceConfig()
    %PAWCLEARANCECONFIG One row per stance-to-observed-swing pair.
    % Time is the swing-peak time; all heights and clearance are in mm.
    config.ProjectType = 'PawClearance';
    config.Fields = {'Cycle'; 'Time'; 'StanceStartIndex'; 'StanceEndIndex'; ...
        'SwingStartIndex'; 'SwingEndIndex'; 'StanceStartTime_s'; ...
        'StanceEndTime_s'; 'SwingStartTime_s'; 'SwingEndTime_s'; ...
        'GroundIndex'; 'GroundTime_s'; 'GroundHeight_mm'; ...
        'PeakIndex'; 'PeakTime_s'; 'PeakToeHeight_mm'; 'PeakPawHeight_mm'};
    config.OptionalFields = {'GroundFrame'; 'PeakFrame'; 'FPS_Hz'; 'LPFCutoff_Hz'; 'SwingEndObserved'};
end
