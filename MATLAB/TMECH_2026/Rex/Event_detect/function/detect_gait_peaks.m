function [main_left, main_right] = ...
    detect_gait_peaks(t, left, right, t_interval)

% =========================================================
% detect_gait_peaks
%
% Left / Right ankle angle에서 gait peak 검출
% =========================================================


%% Settings

smooth_win = 0.01;
min_peak_dist = 0.30;
vel_eps_scale = 0.0;


%% ---------------------------------------------------------
% Left
% ---------------------------------------------------------

v_left = gradient( ...
    left, ...
    median(diff(t)));

vE_left = ...
    vel_eps_scale * std(v_left);

main_left = find_main_peaks_by_minima( ...
    t, ...
    left, ...
    t_interval, ...
    'SmoothWinSec', smooth_win, ...
    'VelEps', vE_left, ...
    'MinPeakDistSec', min_peak_dist, ...
    'MinPeakDistPolicy','keepMax');


%% ---------------------------------------------------------
% Right
% ---------------------------------------------------------

v_right = gradient( ...
    right, ...
    median(diff(t)));

vE_right = ...
    vel_eps_scale * std(v_right);


main_right = find_main_peaks_by_minima( ...
    t, ...
    right, ...
    t_interval, ...
    'SmoothWinSec', smooth_win, ...
    'VelEps', vE_right, ...
    'MinPeakDistSec', min_peak_dist, ...
    'MinPeakDistPolicy','keepMax');

end