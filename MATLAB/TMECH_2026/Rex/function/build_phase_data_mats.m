function [L, R] = build_phase_data_mats(phase, L_intervals, R_intervals, int_data, mode)
% mode: 'exo' or 'mocap' (지금은 로깅용/확장용)

    % ===============================
    % LEFT
    % ===============================
    [L.angle, L.vel, L.torque, L.power] = build_norm_mats_multi( ...
        L_intervals, ...
        int_data.t, ...
        int_data.left.angle, ...
        { ...
            int_data.left.vel, ...
            int_data.left.torque, ...
            int_data.left.power ...
        }, ...
        phase ...
    );

    % ===============================
    % RIGHT
    % ===============================
    [R.angle, R.vel, R.torque, R.power] = build_norm_mats_multi( ...
        R_intervals, ...
        int_data.t, ...
        int_data.right.angle, ...
        { ...
            int_data.right.vel, ...
            int_data.right.torque, ...
            int_data.right.power ...
        }, ...
        phase ...
    );

    % 메타 정보
    L.phase = phase;
    R.phase = phase;

    L.mode = mode;
    R.mode = mode;

end